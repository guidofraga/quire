fn eval(exprs: &[String]) -> Vec<quire_eval::Outcome> {
    let regions: Vec<MathInput> = exprs
        .iter()
        .enumerate()
        .map(|(i, e)| MathInput {
            id: format!("r{i}"),
            expr: e.clone(),
            show: false,
            display: DisplaySpec::default(),
            table: None,
            plot: None,
            symbolic: false,
        })
        .collect();
    Worksheet::new(DisplaySettings::default()).run(&regions)
}

#[test]
fn every_smath_unit_reads_with_smaths_value() -> TestResult {
    let exprs: Vec<String> = SMATH_UNITS.iter().map(|(_, quire, ..)| format!("1 {quire}")).collect();
    let mut wrong = Vec::new();
    for ((name, quire, factor, offset, dim, tol), out) in SMATH_UNITS.iter().zip(eval(&exprs)) {
        match out.value {
            Some(Value::Num(q)) => {
                let want = factor + offset;
                if (q.v - want).abs() > tol * want.abs() || q.dim != Dim::from_ints(*dim) {
                    wrong.push(format!("'{name} ({quire}): {} {:?}, SMath {want} {dim:?}", q.v, q.dim));
                }
            }
            _ => wrong.push(format!("'{name} ({quire}): {}", out.error.unwrap_or_default())),
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} SMath units:
{}",
        wrong.len(),
        SMATH_UNITS.len(),
        wrong.join(
            "
"
        )
    );
    Ok(())
}

#[test]
fn unsupported_smath_units_are_a_clear_error() -> TestResult {
    let exprs: Vec<String> = UNSUPPORTED.iter().map(|n| format!("1 '{n}")).collect();
    for (name, out) in UNSUPPORTED.iter().zip(eval(&exprs)) {
        let err = out.error.ok_or(format!("'{name} should not read"))?;
        assert_eq!(err, format!("unknown unit '{name}"));
    }
    Ok(())
}

#[test]
fn smath_only_names_stay_names_when_bare() -> TestResult {
    // 'e, 'c and 'k are SMath's constants, but a bare e is still Euler's number
    let out = eval(&["2 e".to_string(), "x := 3".to_string(), "2 'e/'C".to_string()]);
    let num = |k: usize| match out.get(k).and_then(|o| o.value.as_ref()) {
        Some(Value::Num(q)) => Some(q.v),
        _ => None,
    };
    assert!(num(0).is_some_and(|v| (v - 2.0 * std::f64::consts::E).abs() < 1e-12));
    assert!(num(2).is_some_and(|v| (v - 3.204_353_268e-19).abs() < 1e-27));
    Ok(())
}
